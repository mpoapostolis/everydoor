#!/usr/bin/env bunx tsx
// scripts/composer-snapshot.mjs — byte-level determinism fixture for the world composer.
//   bunx tsx scripts/composer-snapshot.mjs --write   regenerate tests/fixtures/composer-snapshots.json
//   bunx tsx scripts/composer-snapshot.mjs --check   exit 1 when any (archetype, seed, tier) plan differs
//   bun scripts/composer-snapshot.mjs --check        the same under bun (the plan must not depend on the runtime)
// Each entry stores the sha256 + byte length of the canonical JSON of compose(seed, arch, [], tier)
// (Maps as sorted entry arrays, object keys sorted) plus a human-readable digest, so a drift in any
// number anywhere in the plan fails the check while the fixture stays small.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import { ARCHETYPES, compose } from '../packages/core/src/composer/index.ts';

export const FIXTURE = join(dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'fixtures', 'composer-snapshots.json');
export const SEEDS = [0x5eed0001, 0x5eed0002, 0x5eed0003];
export const CASES = Object.keys(ARCHETYPES).flatMap((archetype) => SEEDS.map((seed, i) => ({ archetype, seed, tier: i % 2 ? 'hard' : 'easy' })));

/** Canonical JSON: Maps → sorted [key, value] arrays, object keys sorted, undefined dropped. */
export function canonical(value) {
  const norm = (v) => {
    if (v instanceof Map) return [...v.entries()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)).map(([k, x]) => [k, norm(x)]);
    if (Array.isArray(v)) return v.map(norm);
    if (v && typeof v === 'object') { const o = {}; for (const k of Object.keys(v).sort()) if (v[k] !== undefined) o[k] = norm(v[k]); return o; }
    return v;
  };
  return JSON.stringify(norm(value));
}

export function snapshot({ archetype, seed, tier }) {
  const map = compose(seed, ARCHETYPES[archetype], [], tier);
  const json = canonical(map);
  return {
    archetype, seed, tier,
    sha256: createHash('sha256').update(json).digest('hex'), bytes: json.length,
    zones: map.zones.map((z) => `${z.id}:${z.role}`), doors: map.doors.length, locked: map.doors.filter((d) => d.lock).length,
    placements: map.placements.length, people: map.people.length, keys: map.keys.length, fallback: map.fallback,
    start: [map.start.x, map.start.z, map.start.yaw], criticalPath: map.criticalPath,
  };
}

export const snapshotAll = () => CASES.map(snapshot);
export const readFixture = () => JSON.parse(readFileSync(FIXTURE, 'utf8'));

/** Differences between a fresh run and the fixture, as strings (empty = identical). */
export function diffFixture(fresh = snapshotAll(), fixture = readFixture()) {
  const out = [];
  const key = (e) => `${e.archetype}/${e.seed}/${e.tier}`;
  const byKey = new Map(fixture.entries.map((e) => [key(e), e]));
  for (const e of fresh) {
    const f = byKey.get(key(e));
    if (!f) { out.push(`${key(e)}: missing from fixture`); continue; }
    if (f.sha256 !== e.sha256 || f.bytes !== e.bytes) out.push(`${key(e)}: sha ${f.sha256.slice(0, 12)}→${e.sha256.slice(0, 12)} bytes ${f.bytes}→${e.bytes} zones ${f.zones.length}→${e.zones.length} placements ${f.placements}→${e.placements}`);
  }
  if (fixture.entries.length !== fresh.length) out.push(`fixture has ${fixture.entries.length} entries, run produced ${fresh.length}`);
  return out;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : '';
  if (!mode) { console.error('usage: composer-snapshot.mjs --write | --check'); process.exit(2); }
  const entries = snapshotAll();
  if (mode === 'write') {
    writeFileSync(FIXTURE, JSON.stringify({ note: 'generated by scripts/composer-snapshot.mjs --write (bunx tsx); --check must pass under tsx AND bun', entries }, null, 1) + '\n');
    console.log(`wrote ${entries.length} snapshots to ${FIXTURE}`);
  } else {
    const diff = diffFixture(entries);
    if (diff.length) { console.error('composer snapshot drift:\n  ' + diff.join('\n  ')); process.exit(1); }
    console.log(`${entries.length} composer snapshots identical (${typeof Bun !== 'undefined' ? 'bun' : 'node ' + process.version})`);
  }
}
